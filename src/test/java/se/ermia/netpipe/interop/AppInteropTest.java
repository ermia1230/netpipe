package se.ermia.netpipe.interop;

import se.ermia.netpipe.crypto.HandshakeCertificate;
import se.ermia.netpipe.crypto.HandshakeCrypto;
import se.ermia.netpipe.crypto.HandshakeDigest;
import se.ermia.netpipe.crypto.SessionCipher;
import se.ermia.netpipe.crypto.SessionKey;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Base64;
import java.util.Properties;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Checks that the JavaScript port of NetPipe used by the chat app (app/netpipe)
 * produces bytes the Java implementation accepts.
 *
 * <p>Vectors are generated by {@code app/netpipe/scripts/generate-interop-vectors.mjs}.
 * AES-CTR and RSA PKCS#1 v1.5 block type 1 are deterministic, so for those the
 * Java output must equal the JavaScript output byte for byte.</p>
 */
@DisplayName("App (JavaScript) interoperability")
class AppInteropTest {

    private static final Base64.Decoder B64 = Base64.getDecoder();
    private static final Properties V = new Properties();

    private static HandshakeCertificate clientCert;
    private static HandshakeCertificate serverCert;
    private static HandshakeCrypto clientPrivate;
    private static HandshakeCrypto serverPrivate;
    private static SessionKey sessionKey;
    private static byte[] iv;

    @BeforeAll
    static void load() throws Exception {
        try (InputStream in = AppInteropTest.class.getResourceAsStream("/interop/app-vectors.properties")) {
            V.load(in);
        }
        clientCert = cert("/certs/client.pem");
        serverCert = cert("/certs/server.pem");
        clientPrivate = new HandshakeCrypto(resource("/certs/client-private.der"));
        serverPrivate = new HandshakeCrypto(resource("/certs/server-private.der"));
        sessionKey = new SessionKey(bytes("session.key"));
        iv = bytes("session.iv");
    }

    @Test
    @DisplayName("SESSION message from JS decrypts with the server's private key")
    void sessionKeyExchange() throws Exception {
        assertThat(serverPrivate.decrypt(bytes("session.SessionKey"))).isEqualTo(sessionKey.getKeyBytes());
        assertThat(serverPrivate.decrypt(bytes("session.SessionIV"))).isEqualTo(iv);
    }

    @Test
    @DisplayName("CLIENTFINISHED signature and timestamp from JS verify in Java")
    void clientFinished() throws Exception {
        HandshakeDigest digest = new HandshakeDigest();
        digest.update(bytes("handshake.clientHello"));
        digest.update(bytes("handshake.session"));
        byte[] expected = digest.digest();

        HandshakeCrypto clientPublic = new HandshakeCrypto(clientCert);
        assertThat(clientPublic.decrypt(bytes("clientFinished.Signature"))).isEqualTo(expected);
        // RSA private-key "encryption" is deterministic: Java must produce the same signature.
        assertThat(clientPrivate.encrypt(expected)).isEqualTo(bytes("clientFinished.Signature"));

        String timestamp = new String(clientPublic.decrypt(bytes("clientFinished.TimeStamp")),
                StandardCharsets.UTF_8);
        LocalDateTime.parse(timestamp, DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
    }

    @Test
    @DisplayName("Client-to-server records equal Java's client SessionCipher stream")
    void clientToServerStream() throws Exception {
        checkDirection("c2s", false, clientCert);
    }

    @Test
    @DisplayName("Server-to-client records equal Java's server SessionCipher stream")
    void serverToClientStream() throws Exception {
        checkDirection("s2c", true, serverCert);
    }

    @Test
    @DisplayName("App identity: self-signed certificate and PKCS#8 key load in Java")
    void appIdentity() throws Exception {
        HandshakeCertificate cert = new HandshakeCertificate(bytes("identity.certificate"));
        cert.verify(cert);
        assertThat(cert.getCN()).isEqualTo(V.getProperty("identity.email"));
        assertThat(cert.getEmail()).isEqualTo(V.getProperty("identity.email"));

        HandshakeCrypto privateKey = new HandshakeCrypto(bytes("identity.privateKey"));
        assertThat(new String(privateKey.decrypt(bytes("identity.encrypted")), StandardCharsets.UTF_8))
                .isEqualTo("netpipe-interop");
    }

    private void checkDirection(String direction, boolean senderIsServer, HandshakeCertificate senderCert)
            throws Exception {
        int count = Integer.parseInt(V.getProperty(direction + ".count"));
        ByteArrayOutputStream plain = new ByteArrayOutputStream();
        ByteArrayOutputStream jsCipher = new ByteArrayOutputStream();
        HandshakeCrypto senderPublic = new HandshakeCrypto(senderCert);

        for (int i = 0; i < count; i++) {
            String prefix = direction + "." + i + ".";
            assertThat(Long.parseLong(V.getProperty(prefix + "offset"))).isEqualTo(plain.size());
            byte[] ciphertext = bytes(prefix + "ciphertext");

            // Record signature: RSA_priv(SHA-256("NetPipe-Record|id|dir|offset|" || ciphertext))
            HandshakeDigest digest = new HandshakeDigest();
            digest.update(("NetPipe-Record|" + V.getProperty("record.sessionId") + "|" + direction + "|"
                    + V.getProperty(prefix + "offset") + "|").getBytes(StandardCharsets.UTF_8));
            digest.update(ciphertext);
            assertThat(senderPublic.decrypt(bytes(prefix + "signature"))).isEqualTo(digest.digest());

            plain.write(bytes(prefix + "plaintext"));
            jsCipher.write(ciphertext);
        }

        // Java sender: encrypting the concatenated plaintext gives the same bytes.
        ByteArrayOutputStream javaCipher = new ByteArrayOutputStream();
        SessionCipher sender = new SessionCipher(sessionKey, iv, senderIsServer);
        try (OutputStream out = sender.openEncryptedOutputStream(javaCipher)) {
            out.write(plain.toByteArray());
        }
        assertThat(javaCipher.toByteArray()).isEqualTo(jsCipher.toByteArray());

        // Java receiver: decrypting the JS ciphertext gives the plaintext.
        SessionCipher receiver = new SessionCipher(sessionKey, iv, !senderIsServer);
        try (InputStream in = receiver.openDecryptedInputStream(
                new ByteArrayInputStream(jsCipher.toByteArray()))) {
            assertThat(in.readAllBytes()).isEqualTo(plain.toByteArray());
        }
    }

    private static byte[] bytes(String key) {
        return B64.decode(V.getProperty(key));
    }

    private static byte[] resource(String name) throws Exception {
        return Files.readAllBytes(Path.of(AppInteropTest.class.getResource(name).toURI()));
    }

    private static HandshakeCertificate cert(String name) throws Exception {
        try (InputStream in = AppInteropTest.class.getResourceAsStream(name)) {
            return new HandshakeCertificate(in);
        }
    }
}
