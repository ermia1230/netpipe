/**
 * Produces values with the JavaScript port of NetPipe for the Java test
 * se.ermia.netpipe.interop.AppInteropTest, which checks them with the real
 * Java classes (SessionCipher, HandshakeCrypto, HandshakeCertificate, ...).
 *
 *   npm run netpipe:vectors     (from app/)
 *
 * Output: src/test/resources/interop/app-vectors.properties
 * All binary values and texts are Base64 so the file is plain ISO-8859-1.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  HandshakeCertificate,
  HandshakeCrypto,
  HandshakeDigest,
  createIdentity,
  encodeBase64,
  privateKeyPemToPkcs8,
  utf8Encode,
} from '../crypto.js';
import {
  MessageType,
  SecureChannel,
  clientFinishedSigns,
  createFinished,
  createHello,
  createSession,
} from '../protocol.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const certs = path.join(root, 'src/test/resources/certs');
const out = path.join(root, 'src/test/resources/interop/app-vectors.properties');

const pem = (name) => fs.readFileSync(path.join(certs, name), 'utf8');
const der = (name) => fs.readFileSync(path.join(certs, name)).toString('binary');
const b64text = (text) => encodeBase64(utf8Encode(text));

const clientCert = HandshakeCertificate.fromPem(pem('client.pem'));
const serverCert = HandshakeCertificate.fromPem(pem('server.pem'));
const clientKey = HandshakeCrypto.fromPrivateKeyBytes(der('client-private.der'));
const serverKey = HandshakeCrypto.fromPrivateKeyBytes(der('server-private.der'));

const props = [];
const put = (key, value) => props.push(`${key}=${value}`);

// Handshake values
const clientHello = createHello(MessageType.CLIENTHELLO, clientCert);
const { message: session, sessionKey, iv } = createSession(serverCert);
const clientFinished = createFinished(
  MessageType.CLIENTFINISHED,
  clientKey,
  clientFinishedSigns({ clientHello, session })
);
put('session.key', encodeBase64(sessionKey.getKeyBytes()));
put('session.iv', encodeBase64(iv));
put('session.SessionKey', session.getParameter('SessionKey'));
put('session.SessionIV', session.getParameter('SessionIV'));
put('handshake.clientHello', encodeBase64(clientHello.getBytes()));
put('handshake.session', encodeBase64(session.getBytes()));
put('clientFinished.Signature', clientFinished.getParameter('Signature'));
put('clientFinished.TimeStamp', clientFinished.getParameter('TimeStamp'));

// Data phase: contiguous records in each direction
const sessionId = 'interop-session';
put('record.sessionId', sessionId);
const channels = {
  c2s: new SecureChannel({
    sessionId, isServer: false, sessionKey, iv,
    privateKey: clientKey, ownCertificate: clientCert, peerCertificate: serverCert,
  }),
  s2c: new SecureChannel({
    sessionId, isServer: true, sessionKey, iv,
    privateKey: serverKey, ownCertificate: serverCert, peerCertificate: clientCert,
  }),
};
const texts = {
  c2s: ['Hej!', 'Ett säkert sms 🔒 over NetPipe', 'x'.repeat(37), '{"candidate":"candidate:1 1 udp 2122260223 10.0.0.2 54400 typ host"}'],
  s2c: ['{"type":"answer","sdp":"v=0\\r\\no=- 46117 2 IN IP4 127.0.0.1\\r\\n"}', 'Tack, mottaget.'],
};
for (const [direction, list] of Object.entries(texts)) {
  let offset = 0;
  put(`${direction}.count`, list.length);
  list.forEach((text, i) => {
    const record = channels[direction].seal(text, offset);
    put(`${direction}.${i}.offset`, record.offset);
    put(`${direction}.${i}.plaintext`, b64text(text));
    put(`${direction}.${i}.ciphertext`, record.ciphertext);
    put(`${direction}.${i}.signature`, record.signature);
    offset += SecureChannel.byteLength(text);
  });
}

// A user identity as the app creates it (self-signed certificate + PKCS#8 key)
const email = 'alice@example.com';
const identity = await createIdentity(email, { validDays: 3650 });
const identityCert = HandshakeCertificate.fromPem(identity.certificatePem);
put('identity.email', email);
put('identity.certificate', identityCert.toBase64());
put('identity.privateKey', encodeBase64(privateKeyPemToPkcs8(identity.privateKeyPem)));
put('identity.encrypted', encodeBase64(HandshakeCrypto.fromCertificate(identityCert).encrypt('netpipe-interop')));

// Sanity check before writing.
const digest = new HandshakeDigest();
digest.update(clientHello.getBytes());
digest.update(session.getBytes());
if (digest.digest().length !== 32) throw new Error('unexpected digest length');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `# Generated by app/netpipe/scripts/generate-interop-vectors.mjs - do not edit.\n${props.join('\n')}\n`
);
console.log(`Wrote ${props.length} values to ${path.relative(root, out)}`);
